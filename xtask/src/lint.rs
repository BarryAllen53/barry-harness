use std::{
    fmt, fs,
    path::{Path, PathBuf},
};

use walkdir::{DirEntry, WalkDir};

use crate::{Outcome, comments::Language};

const ROOT_ONLY_SKIPPED_DIRECTORIES: [&str; 3] = ["target", "dist", "docs"];
const SKIPPED_DIRECTORIES: [&str; 2] = [".git", "node_modules"];

#[derive(Debug, PartialEq, Eq)]
enum Problem {
    Comment { line: usize },
    Unreadable { reason: String },
}

#[derive(Debug, PartialEq, Eq)]
pub struct Finding {
    path: PathBuf,
    problem: Problem,
}

impl fmt::Display for Finding {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.problem {
            Problem::Comment { line } => {
                write!(formatter, "{}:{line}: comment", self.path.display())
            }
            Problem::Unreadable { reason } => {
                write!(formatter, "{}: unreadable: {reason}", self.path.display())
            }
        }
    }
}

pub fn run(root: &Path) -> Outcome {
    let findings = find_comments(root);
    for finding in &findings {
        println!("{finding}");
    }
    if findings.is_empty() {
        println!("lint-comments: no comments found");
        Outcome::Passed
    } else {
        eprintln!("lint-comments: {} problem(s) found", findings.len());
        Outcome::Failed
    }
}

fn find_comments(root: &Path) -> Vec<Finding> {
    let mut findings = Vec::new();
    let entries = WalkDir::new(root)
        .sort_by_file_name()
        .into_iter()
        .filter_entry(|entry| !is_skipped_directory(entry));
    for entry in entries {
        let entry = match entry {
            Ok(entry) => entry,
            Err(error) => {
                let path = error.path().unwrap_or(root);
                findings.push(Finding {
                    path: relative_to(root, path),
                    problem: Problem::Unreadable {
                        reason: error.to_string(),
                    },
                });
                continue;
            }
        };
        if !entry.file_type().is_file() {
            continue;
        }
        let Some(language) = Language::from_path(entry.path()) else {
            continue;
        };
        let path = relative_to(root, entry.path());
        match fs::read_to_string(entry.path()) {
            Ok(source) => {
                let source = source.strip_prefix('\u{feff}').unwrap_or(&source);
                findings.extend(
                    language
                        .comment_lines(source)
                        .into_iter()
                        .map(|line| Finding {
                            path: path.clone(),
                            problem: Problem::Comment { line },
                        }),
                );
            }
            Err(error) => findings.push(Finding {
                path,
                problem: Problem::Unreadable {
                    reason: error.to_string(),
                },
            }),
        }
    }
    findings
}

fn relative_to(root: &Path, path: &Path) -> PathBuf {
    path.strip_prefix(root).unwrap_or(path).to_path_buf()
}

fn is_skipped_directory(entry: &DirEntry) -> bool {
    if entry.depth() == 0 || !entry.file_type().is_dir() {
        return false;
    }
    let Some(name) = entry.file_name().to_str() else {
        return false;
    };
    let parent_name = entry
        .path()
        .parent()
        .and_then(Path::file_name)
        .and_then(|parent| parent.to_str());
    SKIPPED_DIRECTORIES.contains(&name)
        || (entry.depth() == 1 && ROOT_ONLY_SKIPPED_DIRECTORIES.contains(&name))
        || (name == "autogenerated" && parent_name == Some("permissions"))
        || (entry.depth() == 2 && name == "gen" && parent_name == Some("src-tauri"))
}
